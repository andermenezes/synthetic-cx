def test_styled_response_preserves_complete_prose_and_rejects_nested_partition() -> None:
    async def exercise() -> None:
        response = (
            '<div class="flex justify-start"><p class="rounded px-3">'
            "Coverage <strong>includes</strong> all areas.</p><time>10:00</time></div>"
        )
        async with exchange(ECHO + response) as (_, reader):
            candidates = await reader.candidates()
            customer = next(item[1] for item in candidates if item[0] == "customer")
            paragraph = next(
                item[1]
                for item in candidates
                if item[0] == "assistant" and item[3] == "Coverage includes all areas."
            )
            await reader.validate(paragraph, customer)
            with pytest.raises(ChannelError):
                await reader.validate(LocatorConfig(strategy="css", value="strong"), customer)
            with pytest.raises(ChannelError):
                await reader.validate(
                    LocatorConfig(strategy="css", value="div.justify-start, div.justify-start > p"),
                    customer,
                )

    asyncio.run(exercise())


MENU_REPLY = (
    '<div class="flex justify-start"><div class="bubble">'
    '<p class="content">Please choose an option below</p>'
    '<div class="opts"><button>Route one</button><button>Route two</button></div>'
    "<time>10:14</time></div></div>"
)


def test_control_owning_container_readers_are_preferred_over_prose_leaves() -> None:
    """A reply that owns its menu must be learned as the reader container."""

    async def exercise() -> None:
        async with exchange(ECHO + MENU_REPLY) as (_, reader):
            candidates = await reader.candidates()
            assistants = [item for item in candidates if item[0] == "assistant"]
            assert assistants
            # Every offered assistant reader owns the fresh reply controls, and
            # prose-leaf candidates that exclude them are not offered.
            assert all("owns 2 fresh reply controls" in item[3] for item in assistants)
            assert all(
                "justify-start" in item[1].value or "bubble" in item[1].value for item in assistants
            )
            customer = next(item[1] for item in candidates if item[0] == "customer")
            chosen = assistants[0][1]
            await reader.validate(chosen, customer)
            await reader.assert_partition(chosen, customer, TEXT)

    asyncio.run(exercise())


