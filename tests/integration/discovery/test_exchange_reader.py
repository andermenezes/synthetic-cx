@pytest.mark.parametrize("nested", [False, True])
def test_customer_delivery_metadata_is_not_an_assistant_response(nested):
    async def exercise():
        text = f'<p class="rounded">{TEXT}</p>'
        if nested:
            text = '<div class="text">' + text + "</div>"
        markup = '<div class="row">' + text + '<span class="delivery">Delivered</span></div>'
        async with exchange(markup) as (_, reader):
            candidates = await reader.candidates()
            assert not any(item[0] == "assistant" for item in candidates)
            customer = next(item[1] for item in candidates if item[0] == "customer")
            with pytest.raises(ChannelError):
                await reader.validate(
                    LocatorConfig(strategy="css", value="span.delivery"), customer
                )

    asyncio.run(exercise())


