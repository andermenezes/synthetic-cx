def test_repeated_observation_retains_candidate_handles_without_duplicate_inventory() -> None:
    async def exercise() -> None:
        async with exchange(ECHO + REPLY) as (_, reader):
            candidate = (await reader.candidates())[0][2]
            retained_count = len(reader._current)
            for _ in range(3):
                assert await reader.candidates()
            assert len(reader._current) == retained_count
            assert await candidate.evaluate("node => node.isConnected")

    asyncio.run(exercise())


def test_baseline_inventory_limit_cleans_up_handles() -> None:
    async def exercise() -> None:
        async with exchange(ECHO + REPLY) as (page, reader):
            await page.locator("#chat").evaluate(
                "node => {for (let i = 0; i < 2001; i++) "
                "node.append(document.createElement('div'));}"
            )
            with pytest.raises(ChannelError, match="inventory exceeds limit"):
                await reader.begin(TEXT)
            assert reader._before == []
            assert reader._current == []

    asyncio.run(exercise())
