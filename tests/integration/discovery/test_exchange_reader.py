"""Actual local DOM exchanges corroborate generic structural reader hypotheses."""

import asyncio
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

import pytest
from playwright.async_api import Page, async_playwright

from syntheticcx.adapters.channel.ownership import attest_root
from syntheticcx.adapters.channel.reader import ExchangeReaderEvidence
from syntheticcx.config.models import LocatorConfig
from syntheticcx.errors import ChannelError

TEXT = "Tell me about coverage"
ECHO = f'<div class="flex justify-end"><p class="rounded px-3">{TEXT}</p></div>'
REPLY = '<div class="flex justify-start"><p class="rounded px-3">Coverage details</p></div>'


@asynccontextmanager
async def exchange(
    markup: str, *, baseline: str = ""
) -> AsyncIterator[tuple[Page, ExchangeReaderEvidence]]:
    async with async_playwright() as pw:
        browser = await pw.chromium.launch()
        page = await browser.new_page()
        await page.route(
            "**/*",
            lambda route: route.fulfill(
                content_type="text/html",
                body='<section id="chat" role="dialog" aria-label="Chat">'
                + baseline
                + '<input id="composer"></section>',
            ),
        )
        await page.goto("http://localhost:8765/")
        owned = await attest_root(page, page.main_frame, page.locator("#chat"), page.url)
        reader = ExchangeReaderEvidence(owned)
        try:
            await page.evaluate(
                "html => document.querySelector('#composer').addEventListener('keydown', event => {"
                "if (event.key === 'Enter') document.querySelector('#chat')"
                ".insertAdjacentHTML('beforeend', html);})",
                markup,
            )
            await reader.begin(TEXT)
            await page.locator("#composer").fill(TEXT)
            await page.locator("#composer").press("Enter")
            yield page, reader
        finally:
            await reader.close()
            await owned.root.dispose()
            await browser.close()


def test_actual_echo_and_response_compile_ancestor_qualified_leaf_readers() -> None:
    async def exercise() -> None:
        async with exchange(ECHO + REPLY) as (_, reader):
            candidates = await reader.candidates()
            assistant = next(item[1] for item in candidates if item[0] == "assistant")
            customer = next(item[1] for item in candidates if item[0] == "customer")
            assert "justify-start" in assistant.value
            assert "justify-end" in customer.value
            assert TEXT not in assistant.value + customer.value
            assert all(item[1].strategy == "css" for item in candidates)
            await reader.validate(assistant, customer)
            await reader.assert_partition(assistant, customer, TEXT)

    asyncio.run(exercise())


